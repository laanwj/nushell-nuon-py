"""Terminal display width, replicating the `unicode-width` crate 0.1.14 as
nushell uses it for table column alignment. Every rule here is pinned by a
probe against the real binary (see tests/test_conformance.py).

Rules, in order:

- a run of Emoji characters joined by ZWJ (a family emoji, `✔‍✔`) is 2,
  not the sum of its parts — but only when every member is Emoji: `a‍🎉`
  is 1 + 0 + 2
- a pair of regional indicators (a flag) is 2; a lone one is 1
- an Emoji character followed by U+FE0F (emoji presentation, `✌️` or the
  keycap `1️⃣`) is 2; followed by U+FE0E (text presentation) it stays 1
- combining marks (Mn, Me), format characters (Cf: ZWSP, ZWNJ, ZWJ, soft
  hyphen, variation selectors) and emoji modifiers are 0
- otherwise East Asian Width W/F is 2 and everything else 1 (including
  control characters)

The tables are from Unicode 15.1 emoji-data.txt (Emoji and
Extended_Pictographic) — generated, not transcribed by hand.
"""

