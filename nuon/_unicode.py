"""The Unicode White_Space property. The quote-forcing set builds on this;
Python's regex ``\\s`` matches a slightly different set (it includes
U+001C..U+001F), so the ranges are explicit."""

_WHITE_SPACE_STARTS = [a for a, _ in _WHITE_SPACE]
_EMOJI_STARTS = [a for a, _ in _EMOJI]
_EP_STARTS = [a for a, _ in _EXTENDED_PICTOGRAPHIC]
_RI_MIN = 0x1F1E6
_RI_MAX = 0x1F1FF
_VS16 = 0xFE0F
_VS15 = 0xFE0E
_ZWJ = 0x200D
_MODIFIER_MIN = 0x1F3FB
_MODIFIER_MAX = 0x1F3FF


def _in(table: tuple[tuple[int, int], ...], starts: list[int], cp: int) -> bool:
    i = bisect.bisect_right(starts, cp) - 1
    return i >= 0 and table[i][0] <= cp <= table[i][1]


def is_white_space(c: str) -> bool:
    return _in(_WHITE_SPACE, _WHITE_SPACE_STARTS, ord(c))


def is_decimal_digit(c: str) -> bool:
    return unicodedata.category(c) == "Nd"


def display_width(s: str) -> int:
    """The terminal cell count of `s`."""
    width = 0
    i = 0
    n = len(s)
    while i < n:
        cp = ord(s[i])

        # a ZWJ-joined run of Emoji characters is one wide cell; a single
        # Emoji character in such a run position falls through to the
        # per-character rules below
        if _in(_EMOJI, _EMOJI_STARTS, cp):
            j = i + 1
            if j < n and ord(s[j]) in (_VS16, _VS15):
                j += 1
            if j < n and ord(s[j]) == _ZWJ and j + 1 < n and _in(
                _EMOJI, _EMOJI_STARTS, ord(s[j + 1])
            ):
                # consume the whole run: emoji (vs)? (zwj emoji (vs)?)*
                j += 2
                while j < n:
                    k = j
                    if k < n and ord(s[k]) in (_VS16, _VS15):
                        k += 1
                    if k < n and ord(s[k]) == _ZWJ and k + 1 < n and _in(
                        _EMOJI, _EMOJI_STARTS, ord(s[k + 1])
                    ):
                        j = k + 2
                        continue
                    break
                width += 2
                i = j
                continue

        # a flag is one wide cell; a lone indicator is narrow
        if _RI_MIN <= cp <= _RI_MAX:
            if i + 1 < n and _RI_MIN <= ord(s[i + 1]) <= _RI_MAX:
                width += 2
                i += 2
            else:
                width += 1
                i += 1
            continue

        # emoji presentation: `✌️` and keycap `1️⃣` are wide; text
        # presentation `✌︎` is not
        if i + 1 < n and ord(s[i + 1]) in (_VS16, _VS15):
            consumed = 2
            if i + 2 < n and ord(s[i + 2]) == 0x20E3:
                consumed = 3  # a keycap closes with the enclosing mark
            width += 2 if ord(s[i + 1]) == _VS16 else (
                2 if unicodedata.east_asian_width(s[i]) in ("W", "F") else 1
            )
            i += consumed
            continue

        if (
            unicodedata.category(s[i]) in ("Mn", "Me", "Cf")
            or _MODIFIER_MIN <= cp <= _MODIFIER_MAX
        ):
            i += 1
            continue
        width += 2 if unicodedata.east_asian_width(s[i]) in ("W", "F") else 1
        i += 1
    return width
